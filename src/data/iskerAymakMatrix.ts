/**
 * Преобразование записей матрицы в унифицированные MioDistrictItem
 */
export function getIskerAymakDistrictsForRegion(regionId: string, regionName: string): MioDistrictItem[] {
  const records = ISKER_AYMAK_MATRIX[regionId];
  if (!records || records.length === 0) {
    return [];
  }

  return records.map((rec, idx) => {
    const isCity = rec.districtName.toLowerCase().startsWith('г.') || rec.districtName.toLowerCase().startsWith('город');
    const isMonotown = ['Жылыойский', 'Хромтауский', 'г. Рудный', 'г. Лисаковск', 'г. Сарань', 'г. Балхаш', 'г. Темиртау', 'город Сатпаев', 'город Жезказган'].some(m => rec.districtName.includes(m));
    const districtType = isCity ? 'city' : isMonotown ? 'monotown' : 'district';
    const isRepCity = ['astana-city', 'almaty-city', 'shymkent-city'].includes(regionId) ||
      rec.districtName.toLowerCase().includes('астана') ||
      rec.districtName.toLowerCase().includes('шымкент') ||
      (rec.districtName.toLowerCase().includes('алматы') && !rec.districtName.toLowerCase().includes('обл'));

    return {
      id: `${regionId}-${idx}`,
      name: rec.districtName,
      nameKk: rec.districtName,
      regionId,
      type: districtType,
      typeLabel: isCity ? 'Город' : isMonotown ? 'Моногород / Промышленный узел' : 'Район',
      center: rec.districtName.replace(/^(г\.|город)\s*/i, '').trim(),
      specialization: isRepCity
        ? 'Обрабатывающая промышленность («Өрлеу»), машиностроение, IT, медицина, образование, логистика (субсидирование торговли исключено по регламенту Даму)'
        : isCity
          ? 'Обрабатывающая промышленность («Өрлеу»), машиностроение, IT, внутренняя торговля, медицина и логистика'
          : isMonotown
            ? 'Градообразующие производства, горно-металлургический комплекс, машиностроение («Өрлеу»), торговля и МСБ'
            : 'Агропромышленный комплекс, растениеводство, животноводство, переработка сельхозпродукции, сельские квоты «С дипломом — в село!»',
      preferentialRate: '12.6% годовых',
      maxSubsidyText: 'Субсидирование до 12.6%',
      guaranteeText: 'Гарантия Даму до 85%',
      supportedOkeds: buildComprehensiveDistrictOkeds(rec.okeds, districtType, isRepCity)
    };
  });
}
