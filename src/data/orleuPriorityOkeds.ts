/**
 * Функция проверки соответствия введенного ОКЭД программе «Өрлеу».
 * Учитывает вложенность (например, ввод '10.11' матчится на '10.1', 
 * а также прямые совпадения 49.20.0, 52.10.1, 68.20.8 и исключения).
 */
export function checkOrleuEligibility(inputOked: string): { 
  matched: boolean; 
  matchedItem?: OrleuOkedItem; 
  isExcluded?: boolean; 
  exclusionReason?: string;
  reason?: string;
} {
  const clean = inputOked.trim();
  if (!clean) return { matched: false };

  // 1. Проверка прямых исключений из регламента Өрлеу
  if (clean.startsWith('20.15')) {
    return {
      matched: false,
      isExcluded: true,
      exclusionReason: 'ОКЭД 20.15 исключен из программы «Өрлеу» (Производство удобрений и азотосодержащих соединений).'
    };
  }
  if (clean.startsWith('23.51')) {
    return {
      matched: false,
      isExcluded: true,
      exclusionReason: 'ОКЭД 23.51 исключен из программы «Өрлеу» (Производство цемента).'
    };
  }
  if (clean.startsWith('23.63')) {
    return {
      matched: false,
      isExcluded: true,
      exclusionReason: 'ОКЭД 23.63 исключен из программы «Өрлеу» (Производство товарного бетона).'
    };
  }

  // 2. Поиск в утвержденном реестре Өрлеу
  for (const item of ORLEU_PRIORITY_OKEDS) {
    const itemCode = item.code;

    // Единый иерархический matcher: поддерживает группы вида 25.1 -> подкласс 25.11,
    // а также более детальные записи 49.41.0 и аналогичные случаи.
    if (okedHierarchyMatches(clean, itemCode)) {
      const exact = clean === itemCode;
      return {
        matched: true,
        matchedItem: item,
        reason: exact
          ? `ОКЭД ${clean} точно входит в приоритетный перечень «Өрлеу» (${item.section}): ${item.name}`
          : `ОКЭД ${clean} относится к приоритетной группе ${itemCode} программы «Өрлеу» (${item.section}): ${item.name}`
      };
    }
  }

  return { matched: false };
}
